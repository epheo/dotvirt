package netstate

import (
	"cmp"
	"net/netip"
	"sort"
	"strconv"
	"strings"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"

	"github.com/epheo/dotvirt/internal/model"
	"github.com/epheo/dotvirt/internal/netgen"
	"github.com/epheo/dotvirt/internal/reflect"
)

// netView is the UDN, CUDN and NAD stores decoded once per generation: the
// catalog's networks, and the topology the trace asks about before any
// policy runs.
type netView struct {
	networks []model.Network    // the catalog's, by (name, namespace)
	nads     map[string]nadView // by "namespace/name"
	primary  map[string]netID   // a namespace's realized primary UDN or CUDN; absent: the cluster default network
	declares map[string]bool    // namespaces holding a Primary-role UDN, realized or not
	realized map[string]bool    // "namespace/name" of each UDN whose NAD OVN-K generated
	ranges   []primaryRange     // each realized primary UDN and CUDN's range
}

// netID is a network's comparable identity and its name in sentences.
type netID struct{ key, display string }

// nadView is one NAD as the trace reads it.
type nadView struct {
	id       netID
	localnet bool
	// primary: a Primary-role UDN or CUDN generated it, so a pod bound to it
	// has an OVN port on that network, which the cluster controls filter.
	primary  bool
	prefixes []netip.Prefix // its address range; nil when unknown
}

func (s *Snapshot) netView() *netView {
	return s.nets.get(func() [3]uint64 {
		return [3]uint64{reflect.StoreGeneration(s.udn), reflect.StoreGeneration(s.cudn), reflect.StoreGeneration(s.nad)}
	}, func([3]uint64) *netView { return s.decodeNetworks() })
}

func (s *Snapshot) decodeNetworks() *netView {
	v := &netView{
		networks: []model.Network{},
		nads:     map[string]nadView{}, primary: map[string]netID{}, declares: map[string]bool{}, realized: map[string]bool{},
	}
	udns, cudns := sortedList(s.udn), sortedList(s.cudn)
	udnCfg := make(map[string]netgen.NetworkConfig, len(udns))
	for _, u := range udns {
		udnCfg[u.GetNamespace()+"/"+u.GetName()] = udnConfig(u)
	}
	cudnCfg := make(map[string]netgen.NetworkConfig, len(cudns))
	for _, u := range cudns {
		cudnCfg[u.GetName()] = cudnConfig(u)
	}

	// Pass over the NADs first: a CUDN generates one NAD per namespace its
	// namespaceSelector matches, so those namespaces are exactly where the shared
	// network is attachable - collect them, and keep the unowned NADs to surface (a raw
	// NAD not generated by a UDN/CUDN, which those owners already represent). Only
	// an owner the NAD's reference proves by UID counts: a tenant may write any
	// reference into its own namespace's NAD, and a forged one must not publish
	// a shared network to it.
	cudnNS := map[string][]string{}
	var rawNADs []*unstructured.Unstructured
	var cudnNADs [][2]string // (namespace, CUDN) of each CUDN-generated NAD
	for _, u := range sortedList(s.nad) {
		ns, ref := u.GetNamespace(), u.GetNamespace()+"/"+u.GetName()
		n := nadView{id: netID{"nad:" + ref, ref}}
		kind, name := s.owner(u)
		switch kind {
		case "ClusterUserDefinedNetwork":
			cudnNS[name] = append(cudnNS[name], ns)
			cudnNADs = append(cudnNADs, [2]string{ns, name})
			n.id, n.prefixes = netID{"cudn:" + name, name}, parsePrefixes(cudnCfg[name].Subnets())
			n.primary = strings.EqualFold(cudnCfg[name].Role(), "Primary")
		case "UserDefinedNetwork":
			n.id, n.prefixes = netID{"udn:" + ref, name}, parsePrefixes(udnCfg[ns+"/"+name].Subnets())
			if name == u.GetName() {
				v.realized[ref] = true
				n.primary = strings.EqualFold(udnCfg[ref].Role(), "Primary")
			}
		default:
			if !isSystemNamespace(ns) {
				rawNADs = append(rawNADs, u)
			}
		}
		if c, ok := nadConfig(u); ok {
			if kind == "" {
				n.prefixes = parsePrefixes(strings.Split(c.Subnets, ","))
			}
			// A localnet network is its physical network and VLAN: every
			// object mapping the same pair bridges onto one layer-2 domain,
			// whoever declared it. OVN-K maps a localnet without
			// physicalNetworkName under its network name.
			if strings.EqualFold(c.Topology, "localnet") {
				n.localnet = true
				n.id.key = "localnet:" + cmp.Or(c.PhysicalNetworkName, c.Name) + "/" + strconv.Itoa(c.VLANID)
			}
		}
		v.nads[ref] = n
	}

	for _, u := range udns {
		v.networks = append(v.networks, networkFromUDN(u))
		ns, name := u.GetNamespace(), u.GetName()
		cfg := udnCfg[ns+"/"+name]
		if !strings.EqualFold(cfg.Role(), "Primary") {
			continue
		}
		v.declares[ns] = true
		// A primary UDN in a namespace created without the primary-UDN label
		// is never realized; its VMs stay on the default network.
		if !v.realized[ns+"/"+name] {
			continue
		}
		if _, ok := v.primary[ns]; !ok {
			v.primary[ns] = netID{"udn:" + ns + "/" + name, "network " + name}
		}
		v.ranges = append(v.ranges, primaryRange{"udn:" + ns + "/" + name, parsePrefixes(cfg.Subnets()), []string{ns}})
	}
	for _, u := range cudns {
		name := u.GetName()
		n := networkFromCUDN(u)
		n.Namespaces = cudnNS[name]
		v.networks = append(v.networks, n)
		if cfg := cudnCfg[name]; strings.EqualFold(cfg.Role(), "Primary") && len(cudnNS[name]) > 0 {
			v.ranges = append(v.ranges, primaryRange{"cudn:" + name, parsePrefixes(cfg.Subnets()), cudnNS[name]})
		}
	}
	// A namespace's primary UDN wins over a primary CUDN generated there.
	for _, at := range cudnNADs {
		ns, name := at[0], at[1]
		if _, ok := v.primary[ns]; !ok && strings.EqualFold(cudnCfg[name].Role(), "Primary") {
			v.primary[ns] = netID{"cudn:" + name, "shared network " + name}
		}
	}
	for _, nad := range rawNADs {
		v.networks = append(v.networks, networkFromNAD(nad))
	}
	// The stores iterate in hash order, so without this every refetch would
	// reshuffle the topology cards.
	sort.Slice(v.networks, func(i, j int) bool {
		a, b := v.networks[i], v.networks[j]
		if a.Name != b.Name {
			return a.Name < b.Name
		}
		return a.Namespace < b.Namespace
	})
	return v
}
